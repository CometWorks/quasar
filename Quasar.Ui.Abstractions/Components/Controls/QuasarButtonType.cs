namespace Quasar.Ui.Components;

/// <summary>The native button type used by <see cref="QuasarButton"/>.</summary>
public enum QuasarButtonType
{
    /// <summary>A plain button that does not submit a form.</summary>
    Button,

    /// <summary>Submits the surrounding form.</summary>
    Submit,

    /// <summary>Resets the surrounding form.</summary>
    Reset,
}
